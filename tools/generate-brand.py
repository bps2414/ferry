"""Build Ferry's SVG, XAML and raster assets from the same ferry geometry.

Python dependencies: fonttools, pillow, resvg-py (see docs/brand/README.md).
No dependency is added to the application. --check verifies generated vectors.
"""

from __future__ import annotations

import argparse
import io
import math
from pathlib import Path
import struct
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "web/ui/brand"
DURATION = 1.5
EASE = "cubic-bezier(.333333, 1, .666667, 1)"  # ease-out cubic, same curve as interpolate()

# A ferry crossing: cabin and hull in the text color over one blue wave. Flat colors only.
CABIN = "M104 48 H152 Q164 48 164 60 V84 Q164 96 152 96 H104 Q92 96 92 84 V60 Q92 48 104 48 Z"
HULL = "M32 108 H224 L196 158 Q191 166 182 166 H74 Q65 166 60 158 Z"
WAVE = "M40 198 Q62 180 84 198 Q106 216 128 198 Q150 180 172 198 Q194 216 216 198"
WAVE_WIDTH = 20
DARK = {"fg": "#E9EDF3", "ac": "#6F97FF"}
LIGHT = {"fg": "#0D1117", "ac": "#3D6BE0"}
ICON_SCALE = .78  # symbol inside the app-icon tile


def wave_length() -> float:
    # The four quadratic segments are identical: (0,0) (22,-18) (44,0).
    points = [(2 * t * (1 - t) * 22 + t * t * 44, 2 * t * (1 - t) * -18) for t in (i / 400 for i in range(401))]
    return 4 * sum(math.dist(a, b) for a, b in zip(points, points[1:]))


WAVE_DASH = math.ceil(wave_length()) + 2

# time, opacity, y. The wave draws in, the hull and then the cabin rise onto it, then the name.
# The same tracks drive CSS, the native WPF storyboard and the GIF frames.
TRACKS = {
    "hull": [(0, 0, 28), (.3, 0, 28), (.95, 1, 0)],
    "cabin": [(0, 0, 22), (.5, 0, 22), (1.1, 1, 0)],
}
WAVE_TRACK = [(0, 0), (.65, 1)]  # drawn fraction
WORD_TRACK = [(0, 0), (.8, 0), (1.5, 1)]  # revealed fraction


def number(value: float) -> str:
    return f"{value:.3f}".rstrip("0").rstrip(".") or "0"


def wordmark() -> tuple[str, int]:
    """Outline the bundled OFL Geist with spacing tuned for this word."""
    with TTFont(ROOT / "app/fonts/Geist-SemiBold.ttf") as font:
        glyphs = font.getGlyphSet()
        cmap = font.getBestCmap()
        scale = 142 / font["head"].unitsPerEm
        pen = SVGPathPen(glyphs, ntos=number)
        advance = 0
        pairs = {"Fe": -30, "er": -10, "rr": -10, "ry": -30}
        for index, letter in enumerate("Ferry"):
            if index:
                advance += pairs.get("Ferry"[index - 1:index + 1], 0) - 12
            name = cmap[ord(letter)]
            glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, advance * scale, 114)))
            advance += font["hmtx"][name][0]
        return pen.getCommands(), math.ceil(advance * scale)


WORD, WORD_WIDTH = wordmark()
WORD_X = 272
LOGO_WIDTH = WORD_X + WORD_WIDTH + 8


def interpolate(frames: list[tuple], at: float) -> tuple[float, ...]:
    if at <= frames[0][0]:
        return tuple(frames[0][1:])
    for left, right in zip(frames, frames[1:]):
        if at <= right[0]:
            progress = 1 - (1 - (at - left[0]) / (right[0] - left[0])) ** 3
            return tuple(a + (b - a) * progress for a, b in zip(left[1:], right[1:]))
    return tuple(frames[-1][1:])


def symbol(colors: dict, at: float | None = None) -> str:
    def motion(name: str) -> str:
        if at is None:
            return ""
        opacity, y = interpolate(TRACKS[name], at)
        return f' opacity="{number(opacity)}" transform="translate(0 {number(y)})"'

    offset = 0 if at is None else WAVE_DASH * (1 - interpolate(WAVE_TRACK, at)[0])
    return f'''<path class="brand-wave" d="{WAVE}" fill="none" stroke="{colors['ac']}" stroke-width="{WAVE_WIDTH}" stroke-linecap="round" stroke-linejoin="round" stroke-dasharray="{WAVE_DASH}" stroke-dashoffset="{number(offset)}"/>
<g class="brand-hull"{motion('hull')}><path d="{HULL}" fill="{colors['fg']}"/></g>
<g class="brand-cabin"{motion('cabin')}><path d="{CABIN}" fill="{colors['fg']}"/></g>'''


def tile(body: str) -> str:
    return f'''<rect x="9" y="9" width="238" height="238" rx="55" fill="#121821" stroke="#29323F" stroke-width="2"/>
<g transform="translate(128 128) scale({ICON_SCALE}) translate(-128 -128)">{body}</g>'''


def css_keyframes() -> str:
    def frames(track: list[tuple], style) -> list[str]:
        return [f"  {number(frame[0] / DURATION * 100)}% {{ {style(*frame[1:])} }}" for frame in [*track, (DURATION, *track[-1][1:])]]

    rules = [f"/* Generated by tools/generate-brand.py. Animation lasts {DURATION} s, then rests. */"]
    for name, track in TRACKS.items():
        rules += [f"@keyframes brand-{name} {{", *frames(track, lambda o, y: f"opacity: {number(o)}; transform: translateY({number(y)}px);"), "}"]
    rules += ["@keyframes brand-wave {", *frames(WAVE_TRACK, lambda p: f"stroke-dashoffset: {number(WAVE_DASH * (1 - p))};"), "}"]
    rules += ["@keyframes brand-word {", *frames(WORD_TRACK, lambda p: f"opacity: {number(p)}; transform: translateX({number(10 * (1 - p))}px); clip-path: inset(0 {number(100 * (1 - p))}% 0 0);"), "}"]
    for name in [*TRACKS, "wave"]:
        rules.append(f".brand-enter .brand-{name} {{ animation: brand-{name} {DURATION}s {EASE} both; }}")
    rules += [
        f".brand-enter .brand-word, .brand-enter .brand-wordmark {{ animation: brand-word {DURATION}s {EASE} both; }}",
        "@media (prefers-reduced-motion: reduce) {",
        "  .brand-enter [class^=brand-] { animation: none !important; }",
        "}",
    ]
    return "\n".join(rules) + "\n"


CSS = css_keyframes()


def svg(body: str, width: int = 256, height: int = 256, animated: bool = False, color: str = DARK["fg"]) -> str:
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title" color="{color}"{' class="brand-enter"' if animated else ''}>
<title id="title">Ferry</title>
{f'<style>{CSS}</style>' if animated else ''}
{body}
</svg>
'''


def icon(at: float | None = None) -> str:
    return svg(tile(symbol(DARK, at)))


def logo(at: float | None = None, animated: bool = False, colors: dict = DARK, mono: bool = False) -> str:
    if mono:
        colors = {"fg": "currentColor", "ac": "currentColor"}
    word = '<g class="brand-word">'
    if at is not None:
        revealed = interpolate(WORD_TRACK, at)[0]
        word = (f'<defs><clipPath id="word-reveal"><rect width="{number(WORD_WIDTH * revealed)}" height="148"/></clipPath></defs>'
                f'<g class="brand-word" opacity="{number(revealed)}" transform="translate({number(10 * (1 - revealed))} 0)" clip-path="url(#word-reveal)">')
    body = symbol(colors, at) + f'\n<g transform="translate({WORD_X} 64)">{word}<path d="{WORD}" fill="currentColor"/></g></g>'
    return svg(body, LOGO_WIDTH, 256, animated, DARK["fg"] if mono else colors["fg"])


def fragment() -> str:
    return f'''<svg class="logo" viewBox="0 0 256 256" aria-hidden="true" focusable="false">
{tile(symbol(DARK))}
</svg><div class="brand-copy"><img class="brand-wordmark" src="brand/ferry-wordmark.svg" alt="Ferry" width="{WORD_WIDTH}" height="148"><small><span data-i18n="ui.tagline">envio de jogos para PS5</span></small></div>'''


def xaml_geometry() -> str:
    dash = WAVE_DASH / WAVE_WIDTH  # WPF dash lengths are in stroke-thickness units
    parts = [
        f'<Geometry x:Key="FerryCabin">{CABIN}</Geometry>',
        f'<Geometry x:Key="FerryHull">{HULL}</Geometry>',
        f'<Geometry x:Key="FerryWave">{WAVE}</Geometry>',
        f'<DoubleCollection x:Key="FerryWaveDashes">{number(dash)} {number(dash)}</DoubleCollection>',
        f'<Geometry x:Key="FerryWordmark">{WORD}</Geometry>',
    ]

    def animation(target: str, prop: str, frames: list[tuple]) -> str:
        keys = []
        for at, value in [*frames, (DURATION, frames[-1][1])]:
            keys.append(f'<EasingDoubleKeyFrame KeyTime="0:0:{number(at)}" Value="{number(value)}"><EasingDoubleKeyFrame.EasingFunction><CubicEase EasingMode="EaseOut"/></EasingDoubleKeyFrame.EasingFunction></EasingDoubleKeyFrame>')
        return f'<DoubleAnimationUsingKeyFrames Storyboard.TargetName="{target}" Storyboard.TargetProperty="{prop}" Duration="0:0:{number(DURATION)}" FillBehavior="Stop">' + "".join(keys) + '</DoubleAnimationUsingKeyFrames>'

    motions = []
    for name, frames in TRACKS.items():
        native = name.capitalize()
        motions.append(animation(native + "Group", "Opacity", [(f[0], f[1]) for f in frames]))
        motions.append(animation(native + "Offset", "Y", [(f[0], f[2]) for f in frames]))
    motions += [
        animation("Wave", "StrokeDashOffset", [(at, dash * (1 - p)) for at, p in WAVE_TRACK]),
        animation("Wordmark", "Opacity", WORD_TRACK),
        animation("WordmarkOffset", "X", [(at, 10 * (1 - p)) for at, p in WORD_TRACK]),
        animation("WordmarkReveal", "ScaleX", WORD_TRACK),
    ]
    parts.append('<Storyboard x:Key="FerryBrandEnter">' + "\n".join(motions) + '</Storyboard>')
    return '''<!-- Generated by tools/generate-brand.py; shared SVG ferry geometry and Geist outlines. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
''' + "\n".join(parts) + "\n</ResourceDictionary>\n"


def generated() -> dict[Path, str]:
    return {
        BRAND / "ferry-icon.svg": icon(),
        BRAND / "ferry-wordmark.svg": svg(f'<path id="wordmark" d="{WORD}" fill="currentColor"/>', WORD_WIDTH, 148),
        BRAND / "ferry-logo.svg": logo(),
        BRAND / "ferry-logo-light.svg": logo(colors=LIGHT),
        BRAND / "ferry-logo-mono.svg": logo(mono=True),
        BRAND / "ferry-logo-animated.svg": logo(animated=True),
        BRAND / "brand.css": CSS,
        ROOT / "web/ui/logo.svg": icon(),
        ROOT / "app/BrandGeometry.xaml": xaml_geometry(),
    }


def render_svg(source: str, width: int, height: int):
    from PIL import Image
    import resvg_py

    source = source.replace('<svg ', f'<svg width="{width}" height="{height}" ', 1)
    return Image.open(io.BytesIO(resvg_py.svg_to_bytes(svg_string=source))).convert("RGBA")


def render_assets() -> None:
    from PIL import Image, ImageDraw, ImageFont

    sizes = (16, 24, 32, 48, 64, 128, 256)
    images = [render_svg(icon(), size * 4, size * 4).resize((size, size), Image.Resampling.LANCZOS) for size in sizes]
    # Write the seven native ICO frames separately; Pillow's default ICO writer
    # would rescale all small frames from the 256 px image.
    data = []
    for image in images:
        stream = io.BytesIO()
        image.save(stream, format="PNG")
        data.append(stream.getvalue())
    offset = 6 + 16 * len(images)
    entries = []
    for image, png in zip(images, data):
        size = image.width if image.width < 256 else 0
        entries.append(struct.pack("<BBBBHHII", size, size, 0, 0, 1, 32, len(png), offset))
        offset += len(png)
    (ROOT / "app/Ferry.ico").write_bytes(struct.pack("<HHH", 0, 1, len(images)) + b"".join(entries) + b"".join(data))

    # README GIFs: one per GitHub theme, on that theme's page color. They play once and rest
    # on the finished logo (no loop extension).
    count = round(DURATION / .02) + 1
    for name, colors, background in (("ferry-logo-animated.gif", DARK, "#0D1117"), ("ferry-logo-animated-light.gif", LIGHT, "#FFFFFF")):
        frames = []
        for index in range(count):
            frame = render_svg(logo(at=index * .02, colors=colors), LOGO_WIDTH, 256)
            canvas = Image.new("RGBA", frame.size, background)
            canvas.alpha_composite(frame)
            frames.append(canvas.convert("RGB"))
        # One palette for the entire sequence prevents flicker between frames.
        palette = frames[-1].quantize(colors=255, method=Image.Quantize.MEDIANCUT)
        frames = [frame.quantize(palette=palette, dither=Image.Dither.NONE) for frame in frames]
        frames[0].save(ROOT / "docs/brand" / name, save_all=True, append_images=frames[1:], duration=[20] * (count - 1) + [1000], disposal=1, optimize=True)

    # Review sheet: icon, logo on dark and light, native sizes and five formation stages.
    board = Image.new("RGBA", (1440, 1000), "#0A0D12")
    draw = ImageDraw.Draw(board)
    font = ImageFont.truetype(str(ROOT / "app/fonts/Geist-Regular.ttf"), 20)
    draw.text((56, 38), "FERRY / TRAVESSIA", font=font, fill="#8DA2BE")
    board.alpha_composite(render_svg(icon(), 300, 300), (48, 100))
    board.alpha_composite(render_svg(logo(), round(LOGO_WIDTH * 150 / 256), 150), (420, 100))
    light = Image.new("RGBA", (round(LOGO_WIDTH * 150 / 256) + 60, 190), "#F4F6FA")
    light.alpha_composite(render_svg(logo(colors=LIGHT), round(LOGO_WIDTH * 150 / 256), 150), (30, 20))
    board.alpha_composite(light, (950, 80))
    draw.text((420, 300), "16 / 24 / 32 / 48 / 64 / 128 px", font=font, fill="#8DA2BE")
    x = 420
    for image in images[:6]:
        board.alpha_composite(image, (x, 410 - image.height // 2))
        x += image.width + 34
    for index, at in enumerate((.2, .45, .7, 1.0, DURATION)):
        board.alpha_composite(render_svg(icon(at=at), 220, 220), (56 + index * 272, 690))
        draw.text((70 + index * 272, 940), f"{at:.2f} s", font=font, fill="#8DA2BE")
    board.save(ROOT / "docs/brand/preview.png")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated text assets without writes.")
    parser.add_argument("--vectors-only", action="store_true", help="Skip PNG, ICO, GIF and the review sheet.")
    args = parser.parse_args()
    # A task-local dependency install is optional; no global environment change.
    local_dependencies = ROOT / "dist-brand/python"
    if local_dependencies.is_dir():
        sys.path.insert(0, str(local_dependencies))
    files = generated()
    index = ROOT / "web/ui/index.html"
    html = index.read_text(encoding="utf-8")
    for name in ("auth", "shell"):
        start, end = f"<!-- ferry-brand-{name}:start -->", f"<!-- ferry-brand-{name}:end -->"
        if start in html:
            before, rest = html.split(start, 1)
            _, after = rest.split(end, 1)
            html = before + start + fragment() + end + after
    files[index] = html
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in files.items() if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            raise SystemExit("Stale generated assets: " + ", ".join(stale))
        print(f"PASS: {len(files)} generated vector/integration files match the canonical geometry.")
        return
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    (ROOT / "docs/brand").mkdir(parents=True, exist_ok=True)
    if not args.vectors_only:
        render_assets()
    print(f"Generated {len(files)} vector/integration files; wordmark {WORD_WIDTH} x 148; logo {LOGO_WIDTH} x 256.")


if __name__ == "__main__":
    main()
